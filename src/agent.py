import os
from openai import OpenAI

SYSTEM = """You are DealMind, a sales intelligence copilot. You help a sales representative prepare for and follow up with prospects.
Use the recalled memories as evidence about the account. Never invent facts. Clearly distinguish remembered facts from suggestions.
Be concise and practical. When useful, organize the answer as: Account context, Risks/objections, Recommended action, Suggested message.
The goal is to make future interactions more personalized because the agent remembers previous interactions."""

class SalesAgent:
    def __init__(self):
        key = os.getenv("GROQ_API_KEY")
        self.model = os.getenv("GROQ_MODEL", "openai/gpt-oss-120b")
        self.client = OpenAI(
            api_key=key or "demo-key",
            base_url=os.getenv("GROQ_BASE_URL", "https://api.groq.com/openai/v1"),
        ) if key else None

    def answer(self, user_message, memories):
        if not self.client:
            return self.fallback(user_message, memories)
        memory_text = "\n".join(f"- {m['text']}" for m in memories) or "- No relevant prior memory found."
        prompt = f"""User request:\n{user_message}\n\nRelevant Hindsight memories:\n{memory_text}\n\nAnswer the user using only supported account facts. If there is no memory, say so and provide a sensible next step."""
        response = self.client.chat.completions.create(
            model=self.model,
            temperature=0.2,
            messages=[{"role":"system","content":SYSTEM},{"role":"user","content":prompt}],
        )
        return response.choices[0].message.content

    def fallback(self, user_message, memories):
        if memories:
            bullets = "\n".join(f"• {m['text']}" for m in memories[:5])
            return f"**Relevant account memory**\n\n{bullets}\n\n**Recommended next step**\nUse these remembered objections and commitments to tailor the next customer interaction.\n\n*Groq API key is not configured, so this response is generated by the demo fallback.*"
        return "No relevant Hindsight memories were found. Capture the prospect's objections, stakeholders, competitors, and commitments after the interaction so future sessions can use them."
